namespace KillSwitchLauncher.Models;

/// <summary>
/// Копии приложений, запущенные мимо лаунчера (с рабочего стола, автозагрузкой, по ссылке из другой программы), и процессы
/// приложения через подключение лаунчера, о которых лаунчер не успел ответить ядру. Ядро узнаёт их по exe-файлам приложения.
/// «Через VPN», «Без интернета» и «Напрямую» — только для приложений через подключение лаунчера, «Через лаунчер» — для всех.
/// Новое значение добавляется в конец: в старых файлах настроек значения могут быть записаны числом.
/// </summary>
public enum OutsideCopies
{
    /// <summary>Через подключение приложения, как и само приложение.</summary>
    Vpn,

    /// <summary>Без сети.</summary>
    Block,

    /// <summary>Напрямую, как остальные программы компьютера.</summary>
    Allow,

    /// <summary>
    /// Как запуск с плитки: лаунчер берёт копию под контроль, если приложение сейчас можно запустить, иначе закрывает её.
    /// Пока копию не взяли под контроль, ядро ведёт её, как при <see cref="Vpn"/>.
    /// </summary>
    Launcher
}

/// <summary>«Если открыто не из лаунчера» на странице приложения: своё значение поверх общих настроек.</summary>
public enum OutsideCopiesOverride
{
    /// <summary>Как в общих настройках.</summary>
    Inherit,

    Vpn,

    Block,

    Allow,

    Launcher
}
